const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const ctx = await browser.newContext({ viewport: { width: 430, height: 932 }, deviceScaleFactor: 3, isMobile: true, hasTouch: true, locale: 'zh-TW' });
  const page = await ctx.newPage();
  await page.goto('https://lifenum.pages.dev/', { waitUntil: 'domcontentloaded' });
  await page.waitForTimeout(3500);
  await page.screenshot({ path: 'D:/LifeNum/.shots/onboard.png' });
  const filled = await page.evaluate(() => {
    const ins = Array.from(document.querySelectorAll('input'));
    const date = ins.find(i => i.type === 'date') || ins[1];
    if (!date) return 'no date input';
    const setter = Object.getOwnPropertyDescriptor(window.HTMLInputElement.prototype, 'value').set;
    setter.call(date, '1990-05-15');
    date.dispatchEvent(new Event('input', { bubbles: true }));
    date.dispatchEvent(new Event('change', { bubbles: true }));
    return 'filled';
  });
  await page.waitForTimeout(1200);
  await page.evaluate(() => { const b = Array.from(document.querySelectorAll('button')).find(e => (e.innerText||'').includes('開始探索')); if (b) b.click(); });
  await page.waitForTimeout(3000);
  await page.screenshot({ path: 'D:/LifeNum/.shots/s1.png' });
  await page.evaluate(() => { const m = document.querySelector('main'); if (m) m.scrollTop = 640; window.scrollTo(0, 640); });
  await page.waitForTimeout(1200);
  await page.screenshot({ path: 'D:/LifeNum/.shots/s2.png' });
  await page.evaluate(() => { const m = document.querySelector('main'); if (m) m.scrollTop = 0; window.scrollTo(0,0); const b = Array.from(document.querySelectorAll('nav button')).find(e => (e.innerText||'').includes('我的')); if (b) b.click(); });
  await page.waitForTimeout(2000);
  await page.screenshot({ path: 'D:/LifeNum/.shots/s3.png' });
  console.log(filled);
  await browser.close();
})();
